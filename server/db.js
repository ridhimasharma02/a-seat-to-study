// Tables, first-run demo data and small helpers. Works on Supabase (Postgres) and on local SQLite.
import { randomInt } from 'node:crypto';
import { hashPassword } from './auth.js';
import { openStore } from './store.js';
import { DEMO_ACCOUNTS, STAFF_ACCOUNTS, SPACES, MIN, targetShare } from './config.js';

const TABLES = ['reports', 'bookings', 'sessions', 'seats', 'spaces', 'settings', 'users']; // drop order
const SCHEMA_VERSION = '3'; // bump when tables, columns or staff accounts change

function schema(dialect) {
  const pg = dialect === 'pg';
  const id = pg ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  const ref = pg ? 'BIGINT' : 'INTEGER';
  const ms = pg ? 'BIGINT' : 'INTEGER';     // times are stored as milliseconds since 1970
  const real = pg ? 'DOUBLE PRECISION' : 'REAL';
  return [
    `CREATE TABLE IF NOT EXISTS users (
      id ${id},
      reg_no TEXT NOT NULL UNIQUE,            -- student registration number, or Staff ID for staff
      name TEXT NOT NULL,
      pass_hash TEXT NOT NULL,
      role TEXT NOT NULL DEFAULT 'student',   -- student | staff
      title TEXT,                             -- staff job title
      is_demo INTEGER NOT NULL DEFAULT 0,
      created_at ${ms} NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS sessions (
      token TEXT PRIMARY KEY,
      user_id ${ref} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at ${ms} NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS spaces (
      id TEXT PRIMARY KEY, name TEXT NOT NULL, area TEXT NOT NULL, block TEXT NOT NULL, kinds TEXT NOT NULL,
      layout TEXT NOT NULL, cols INTEGER NOT NULL, sort INTEGER NOT NULL, base ${real} NOT NULL, blurb TEXT NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS seats (
      id ${id},
      space_id TEXT NOT NULL REFERENCES spaces(id),
      label TEXT NOT NULL, grp TEXT NOT NULL, pos INTEGER NOT NULL,
      power INTEGER NOT NULL DEFAULT 0, power_ok INTEGER NOT NULL DEFAULT 1, capacity INTEGER NOT NULL DEFAULT 1,
      code TEXT NOT NULL,
      UNIQUE (space_id, label))`,
    `CREATE TABLE IF NOT EXISTS bookings (
      id ${id},
      user_id ${ref} NOT NULL REFERENCES users(id),
      seat_id ${ref} NOT NULL REFERENCES seats(id),
      start_at ${ms} NOT NULL, end_at ${ms} NOT NULL,
      status TEXT NOT NULL,                   -- reserved | checked_in | on_break | completed | cancelled | no_show | released
      checked_in_at ${ms}, break_started_at ${ms}, breaks_used INTEGER NOT NULL DEFAULT 0,
      ended_at ${ms}, end_reason TEXT,
      is_demo INTEGER NOT NULL DEFAULT 0,
      plan TEXT,                              -- demo behaviour only: 'noshow' | 'overrun'
      created_at ${ms} NOT NULL)`,
    'CREATE INDEX IF NOT EXISTS bookings_seat ON bookings (seat_id, status, start_at, end_at)',
    'CREATE INDEX IF NOT EXISTS bookings_user ON bookings (user_id, status)',
    'CREATE INDEX IF NOT EXISTS bookings_status ON bookings (status, start_at)',
    `CREATE TABLE IF NOT EXISTS reports (
      id ${id},
      seat_id ${ref} NOT NULL REFERENCES seats(id),
      user_id ${ref} NOT NULL REFERENCES users(id),
      reason TEXT NOT NULL,                   -- bag | socket | noise | other
      note TEXT,
      status TEXT NOT NULL DEFAULT 'open',
      resolution TEXT,
      resolved_by ${ref} REFERENCES users(id),
      staff_note TEXT,
      created_at ${ms} NOT NULL,
      resolved_at ${ms})`,
    'CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL)',
  ];
}

export async function openDb({ url, file, reset = false }) {
  const db = await openStore({ url, file });
  // Already set up? Skip the setup steps below (they take a while over the network, e.g. on every Vercel cold start).
  if (!reset) {
    let current = null;
    try { current = (await db.get("SELECT value FROM settings WHERE key = 'schema_version'"))?.value; } catch { /* no tables yet */ }
    if (current === SCHEMA_VERSION) return db;
  }
  if (reset) {
    for (const t of TABLES) await db.exec(`DROP TABLE IF EXISTS ${t}${db.dialect === 'pg' ? ' CASCADE' : ''}`);
  }
  for (const sql of schema(db.dialect)) await db.exec(sql);

  // databases made by an older version of the app get the newer columns
  const addColumn = async (table, col, def) => {
    if (db.dialect === 'pg') return db.exec(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${col} ${def}`);
    const cols = await db.all(`PRAGMA table_info(${table})`);
    if (!cols.some((c) => c.name === col)) await db.exec(`ALTER TABLE ${table} ADD COLUMN ${col} ${def}`);
  };
  await addColumn('users', 'title', 'TEXT');
  await addColumn('reports', 'resolved_by', 'INTEGER REFERENCES users(id)');
  await addColumn('reports', 'staff_note', 'TEXT');

  if (db.dialect === 'pg') {
    // Supabase also publishes the `public` schema through its web API. Row-level security with no policies
    // closes that door; this server connects as the table owner, so it is not affected.
    for (const t of TABLES) await db.exec(`ALTER TABLE ${t} ENABLE ROW LEVEL SECURITY`);
  }

  if ((await db.get('SELECT COUNT(*) AS n FROM spaces')).n === 0) await seed(db);
  await ensureStaff(db);
  await setSetting(db, 'schema_version', SCHEMA_VERSION);
  return db;
}

export async function getSetting(db, key, fallback) {
  const row = await db.get('SELECT value FROM settings WHERE key = ?', key);
  return row ? row.value : fallback;
}
export async function setSetting(db, key, value) {
  await db.run('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value', key, String(value));
}

const CODE_ALPHABET = 'ACDEFGHJKMNPQRTUVWXY34679';
export const deskCode = () => Array.from({ length: 4 }, () => CODE_ALPHABET[randomInt(CODE_ALPHABET.length)]).join('');

// Insert many rows with a few big statements instead of one round trip per row.
export async function insertMany(t, table, cols, rows, chunk = 400) {
  for (let i = 0; i < rows.length; i += chunk) {
    const part = rows.slice(i, i + chunk);
    const one = `(${cols.map(() => '?').join(', ')})`;
    await t.run(`INSERT INTO ${table} (${cols.join(', ')}) VALUES ${part.map(() => one).join(', ')}`, ...part.flat());
  }
}

// Small seeded random generator so the floor plans come out the same every time.
function seeded(seed) {
  return () => {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function layoutSeats(sp, rnd) {
  const seats = [];
  const power = (chance) => {
    const has = rnd() < chance ? 1 : 0;
    return { power: has, power_ok: has && rnd() < 0.12 ? 0 : 1 };
  };
  if (sp.layout === 'tables6' || sp.layout === 'tables4') {
    const per = sp.layout === 'tables6' ? 6 : 4;
    for (let t = 0; t < sp.count; t++) {
      const grp = String.fromCharCode(65 + t);
      for (let p = 0; p < per; p++) seats.push({ label: `${grp}${p + 1}`, grp, pos: p, capacity: 1, ...power(0.42) });
    }
  } else if (sp.layout === 'carrels') {
    for (let i = 0; i < sp.count; i++) {
      const row = Math.floor(i / sp.cols);
      seats.push({ label: `Q${String(i + 1).padStart(2, '0')}`, grp: `Row ${row + 1}`, pos: i % sp.cols, capacity: 1, ...power(0.6) });
    }
  } else {
    for (let i = 0; i < sp.count; i++) seats.push({ label: `Room ${i + 1}`, grp: `Room ${i + 1}`, pos: 0, capacity: sp.capacity, power: 1, power_ok: 1 });
  }
  return seats;
}

// Staff accounts live in the users table with role 'staff' and their Staff ID in reg_no.
async function ensureStaff(db) {
  for (const s of STAFF_ACCOUNTS) {
    if (await db.get('SELECT 1 AS x FROM users WHERE reg_no = ?', s.staff_id)) continue;
    await db.run("INSERT INTO users (reg_no, name, pass_hash, role, title, created_at) VALUES (?, ?, ?, 'staff', ?, ?)",
      s.staff_id, s.name, hashPassword(s.password), s.title, Date.now());
  }
}

async function seed(db) {
  const rnd = seeded(37);
  const now = Date.now();
  console.log('  Setting up the database with demo data (first run only)…');
  await db.tx(async (t) => {
    await t.run("INSERT INTO users (reg_no, name, pass_hash, role, is_demo, created_at) VALUES (?, ?, ?, 'student', 0, ?)",
      DEMO_ACCOUNTS.student.reg_no, DEMO_ACCOUNTS.student.name, hashPassword(DEMO_ACCOUNTS.student.password), now);
    // Simulated students who fill the seats. They can't log in.
    await insertMany(t, 'users', ['reg_no', 'name', 'pass_hash', 'role', 'is_demo', 'created_at'],
      Array.from({ length: 120 }, (_, i) => [`demo-${String(i + 1).padStart(3, '0')}`, `Demo student ${i + 1}`, 'disabled', 'student', 1, now]));
    await insertMany(t, 'spaces', ['id', 'name', 'area', 'block', 'kinds', 'layout', 'cols', 'sort', 'base', 'blurb'],
      SPACES.map((sp, i) => [sp.id, sp.name, sp.area, sp.block, sp.kinds.join(','), sp.layout, sp.cols, i, sp.base, sp.blurb]));
    await insertMany(t, 'seats', ['space_id', 'label', 'grp', 'pos', 'power', 'power_ok', 'capacity', 'code'],
      SPACES.flatMap((sp) => layoutSeats(sp, rnd).map((s) => [sp.id, s.label, s.grp, s.pos, s.power, s.power_ok, s.capacity, deskCode()])));
    await t.run("INSERT INTO settings (key, value) VALUES ('demo_activity', '1')");
  });
  await seedHistory(db, rnd, now);
}

// Two weeks of past bookings by the simulated students, so the Insights page has something to show.
async function seedHistory(db, rnd, now) {
  const demoIds = (await db.all('SELECT id FROM users WHERE is_demo = 1 ORDER BY id')).map((r) => r.id);
  const seats = await db.all('SELECT seats.id, spaces.base FROM seats JOIN spaces ON spaces.id = seats.space_id ORDER BY seats.id');
  const rows = [];
  const today = new Date(now); today.setHours(0, 0, 0, 0);
  for (let d = 14; d >= 1; d--) {
    const day = new Date(today); day.setDate(day.getDate() - d);
    const open = new Date(day); open.setHours(8, 0, 0, 0);
    const close = new Date(day); close.setHours(22, 30, 0, 0);
    for (const seat of seats) {
      let t = open.getTime();
      while (t < close.getTime()) {
        const share = targetShare(seat.base, new Date(t).getHours());
        if (rnd() < Math.min(0.95, share * 0.95)) {
          const start = t + Math.floor(rnd() * 4) * 5 * MIN;
          const end = start + (2 + Math.floor(rnd() * 5)) * 30 * MIN;
          const user = demoIds[Math.floor(rnd() * demoIds.length)];
          if (rnd() < 0.08) {
            rows.push([user, seat.id, start, end, 'no_show', null, start + 15 * MIN, 'Not checked in within 15 minutes', 1, start - 30 * MIN]);
          } else {
            const checkedIn = start + Math.floor(rnd() * 10) * MIN;
            const leftEarly = rnd() < 0.3 ? Math.floor(rnd() * (end - start) * 0.5) : 0;
            rows.push([user, seat.id, start, end, 'completed', checkedIn, end - leftEarly, leftEarly ? 'Checked out' : 'Time ended', 1, start - 30 * MIN]);
          }
          t = end + (1 + Math.floor(rnd() * 6)) * 10 * MIN;
        } else {
          t += 60 * MIN;
        }
      }
    }
  }
  await db.tx((t) => insertMany(t, 'bookings',
    ['user_id', 'seat_id', 'start_at', 'end_at', 'status', 'checked_in_at', 'ended_at', 'end_reason', 'is_demo', 'created_at'], rows, 800));
  console.log(`  Added ${rows.length} past demo bookings for the Insights page.`);
}
